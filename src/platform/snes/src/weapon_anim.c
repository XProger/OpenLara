/* Pistol arm state, from Lara::weapon{Draw,Holster,Update}Pistols.
   The level's frame ranges are generated by the packer, in olweapon.h. */
#include "weapon.h"
#include "lara.h"
#include "olweapon.h"

WeaponArm olWeaponArms[2];
LaraLook olLaraLook;

/* Kept as the formula reference. The cartridge uses weapon_anim.asm to
   fit the controller in the remaining resident code space. */
#ifdef OL_HOST_BUILD
void Lara_resetLook(void)
{
    olLaraLook.torsoX = olLaraLook.torsoY = 0;
    olLaraLook.headX = olLaraLook.headY = 0;
}

/* updateLook runs before movement and weaponUpdate, so it reads the
   preceding tick's arm angles and aim flags. Manual look and camera-item
   tracking wait for those camera modes. */
static int16 Lara_lookAngle(int16 a, int16 b, int16 current)
{
    if (olWeaponTarget != OL_NO_ACTIVE) {
        int32 sum = (int32)a + b;
        int shift = olWeaponAim == WEAPON_AIM_BOTH ? 2 : 1;
        return (int16)(sum < 0 ? -((-sum + (1 << shift) - 1) >> shift) : sum >> shift);
    } else {
        int32 magnitude = current < 0 ? -(int32)current : current;
        int step = (int)(magnitude >> 3);
        int delta = (int16)(uint16)(-current);
        /* angleDec follows the short signed arc, including -32768. */
        if (delta > step) return (int16)(uint16)(current + step);
        if (delta < -step) return (int16)(uint16)(current - step);
        return 0;
    }
}

void Lara_updateLook(void)
{
    if (items[0].health <= 0) {
        Lara_resetLook();
        return;
    }
    olLaraLook.torsoX = olLaraLook.headX = Lara_lookAngle(
        olWeaponArms[0].angleX, olWeaponArms[1].angleX, olLaraLook.headX);
    olLaraLook.torsoY = olLaraLook.headY = Lara_lookAngle(
        olWeaponArms[0].angleY, olWeaponArms[1].angleY, olLaraLook.headY);
}

void Weapon_resetArms(void)
{
    unsigned int i;
    for (i = 0; i < 2; i++) {
        WeaponArm* arm = olWeaponArms + i;
        arm->anim = PISTOL_ANIM_NONE;
        arm->frame = arm->useBasis = 0;
        arm->angleX = arm->angleY = 0;
    }
}

static int Weapon_lerp(int angle, int target)
{
    int delta = (int16)(uint16)(target - angle);
    if (delta > ANGLE_1 * 10) delta = ANGLE_1 * 10;
    if (delta < -ANGLE_1 * 10) delta = -ANGLE_1 * 10;
    return angle + delta;
}

void Weapon_animate(unsigned int input)
{
    unsigned int i;
    for (i = 0; i < 2; i++) {
        WeaponArm* arm = olWeaponArms + i;
        unsigned int anim = arm->anim;
        unsigned int frame = arm->frame;
        unsigned int aiming = olWeaponAim & (i ? WEAPON_AIM_LEFT : WEAPON_AIM_RIGHT);

        if (olLaraWeaponState == WEAPON_STATE_DRAW) {
            frame++;
            if (frame > (anim == PISTOL_ANIM_PICK ? PISTOL_PICK_LAST : PISTOL_DRAW_LAST)) {
                frame = 0;
                if (anim == PISTOL_ANIM_PICK) {
                    anim = PISTOL_ANIM_DRAW;
                    arm->drawn = 1;
                } else {
                    anim = PISTOL_ANIM_AIM;
                }
            }
            arm->angleX = arm->angleY = 0;
            arm->useBasis = 0;
        } else if (olLaraWeaponState == WEAPON_STATE_HOLSTER) {
            if (anim == PISTOL_ANIM_NONE) continue;
            if (frame) {
                if (anim == PISTOL_ANIM_AIM) {
                    arm->angleX -= arm->angleX / (int)frame;
                    arm->angleY -= arm->angleY / (int)frame;
                }
                frame = anim == PISTOL_ANIM_FIRE ? 0 : frame - 1;
            } else {
                if (anim == PISTOL_ANIM_AIM) { anim = PISTOL_ANIM_DRAW; frame = PISTOL_DRAW_LAST; }
                else if (anim == PISTOL_ANIM_DRAW) {
                    anim = PISTOL_ANIM_PICK; frame = PISTOL_PICK_LAST; arm->drawn = 0;
                } else if (anim == PISTOL_ANIM_FIRE) { anim = PISTOL_ANIM_AIM; frame = PISTOL_AIM_LAST; }
                else { anim = PISTOL_ANIM_NONE; }
            }
        } else if (olLaraWeaponState == WEAPON_STATE_READY) {
            arm->angleX = Weapon_lerp(arm->angleX, aiming ? olWeaponAimX : 0);
            arm->angleY = Weapon_lerp(arm->angleY, aiming ? olWeaponAimY : 0);
            if (((input & IN_ACTION) && olWeaponTarget == OL_NO_ACTIVE) || aiming) {
                if (anim == PISTOL_ANIM_AIM) {
                    if (frame == PISTOL_AIM_LAST) {
                        if (input & IN_ACTION) {
#ifdef OL_FX3
                            olWeaponFireArm = (unsigned int)((char*)arm - (char*)olWeaponArms);
#endif
                            Weapon_fire(aiming);
                            anim = PISTOL_ANIM_FIRE; frame = 0;
                        }
                    } else frame++;
                } else if (++frame == PISTOL_RELOAD) {
                    anim = PISTOL_ANIM_AIM; frame = PISTOL_AIM_LAST;
                }
            } else if (anim == PISTOL_ANIM_FIRE) {
                anim = PISTOL_ANIM_AIM; frame = PISTOL_AIM_LAST;
            } else if (frame) frame--;
            arm->useBasis = (anim == PISTOL_ANIM_FIRE || frame != 0);
        } else {
            Weapon_resetArms();
            return;
        }
        arm->anim = anim;
        arm->frame = frame;
    }
    if (olLaraWeaponState == WEAPON_STATE_DRAW && olWeaponArms[1].anim == PISTOL_ANIM_AIM)
        olLaraWeaponState = WEAPON_STATE_READY;
    if (olLaraWeaponState == WEAPON_STATE_HOLSTER &&
        olWeaponArms[0].anim == PISTOL_ANIM_NONE && olWeaponArms[1].anim == PISTOL_ANIM_NONE) {
        olLaraWeaponState = WEAPON_STATE_FREE;
        Weapon_resetArms();
    }
}
#endif
