#!/usr/bin/env python3
"""Emit the GSU's sine table and the placeholder cube model.

Both are assembled into the GSU program blob so they sit in the same ROM bank
the code runs from, which means ROMBR stays put while reading them.

Sine table
    256 entries covering a full turn, signed 1.15 fixed point. The matrix
    builder wants |value| <= 1.0 so that FMULT (which returns the high word of
    a 16x16 product, i.e. a >> 16) can be used directly as a fixed-point
    multiply.

Cube
    Eight vertices at +/- HALF, six quad faces. A face is four (vertex index,
    u, v) triples, wound clockwise as seen from outside, which is what the
    backface test and the rasterizer's prev/next walk both expect.
"""

import math
import struct
import sys

HALF = 1024


def sine_table():
    data = bytearray()
    for i in range(256):
        v = int(round(math.sin(i * 2.0 * math.pi / 256.0) * 32767.0))
        data += struct.pack('<h', max(-32768, min(32767, v)))
    return data


def cube():
    verts = [
        (-HALF, -HALF, -HALF),  # 0
        ( HALF, -HALF, -HALF),  # 1
        ( HALF,  HALF, -HALF),  # 2
        (-HALF,  HALF, -HALF),  # 3
        (-HALF, -HALF,  HALF),  # 4
        ( HALF, -HALF,  HALF),  # 5
        ( HALF,  HALF,  HALF),  # 6
        (-HALF,  HALF,  HALF),  # 7
    ]

    # Clockwise seen from outside the cube.
    faces = [
        (0, 1, 2, 3),   # front  (-z)
        (5, 4, 7, 6),   # back   (+z)
        (4, 0, 3, 7),   # left
        (1, 5, 6, 2),   # right
        (4, 5, 1, 0),   # top
        (3, 2, 6, 7),   # bottom
    ]

    # One texture page, each face taking the whole of it.
    uv = [(0, 0), (255, 0), (255, 255), (0, 255)]

    vdata = bytearray()
    for x, y, z in verts:
        vdata += struct.pack('<hhh', x, y, z)

    fdata = bytearray()
    for f in faces:
        for i, vi in enumerate(f):
            fdata += bytes([vi, uv[i][0], uv[i][1]])

    return vdata, fdata, len(verts), len(faces)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "model.bin"
    sin_data = sine_table()
    vdata, fdata, nv, nf = cube()

    with open(out, "wb") as f:
        f.write(bytes(sin_data + vdata + fdata))

    print(f"{out}: sine {len(sin_data)}B at 0, "
          f"{nv} verts {len(vdata)}B at {len(sin_data)}, "
          f"{nf} faces {len(fdata)}B at {len(sin_data) + len(vdata)}")

    # The assembler needs the offsets; emit them as an include.
    inc = out.rsplit('.', 1)[0] + "_off.inc"
    with open(inc, "w") as f:
        f.write("; generated by tools/mkmodel.py -- do not edit\n")
        f.write(f".DEFINE MODEL_SIN    {0}\n")
        f.write(f".DEFINE MODEL_VERTS  {len(sin_data)}\n")
        f.write(f".DEFINE MODEL_FACES  {len(sin_data) + len(vdata)}\n")
        f.write(f".DEFINE MODEL_NVERTS {nv}\n")
        f.write(f".DEFINE MODEL_NFACES {nf}\n")
    print(f"{inc}: offsets")


if __name__ == "__main__":
    main()
