#!/usr/bin/env python3
"""Extract upstream's sphere collision verbatim for tools/spherecheck.cpp.

ItemObj::getFrames/getFrame/getBoundingBox/getSpheres/collideSpheres/getJoint
from item.h, GBA's C matrix functions, sine and reciprocal tables from
common.cpp, and the macros they use
from common.h (little-endian DECODE_ANGLES). Nothing here is rewritten."""
import re
import sys
from pathlib import Path

from mkenemystate import braced


def define(source, name):
    m = re.search(rf'^#define {name}\b.*?(?<!\\)$', source, re.M | re.S)
    if not m:
        raise ValueError(f'no #define {name}')
    return m.group(0)


def function(source, signature):
    m = re.search(rf'^{signature}', source, re.M)
    if not m:
        raise ValueError(f'no {signature}')
    return braced(source, m.start())


def main(fixed, out):
    fixed = Path(fixed)
    common_h = (fixed / 'common.h').read_text()
    common_cpp = (fixed / 'common.cpp').read_text()
    item_h = (fixed / 'item.h').read_text()
    little = common_h[common_h.index('#ifdef CPU_BIG_ENDIAN\n#define DECODE_ANGLES'):]
    little = little[little.index('#else') + 5:little.index('#endif')].strip()
    parts = ['// Generated by tools/mkspherecheck.py from src/fixed; do not edit.']
    for name in ('X_ROTX', 'X_ROTY', 'X_ROTXY', 'DP33', 'sincos'):
        parts.append(define(common_h, name))
    parts.append(little)
    parts.append(define(common_cpp, 'MATRIX_TRANS'))
    table = re.search(r'^const uint32 gSinCosTable\[4096\] = .*?^\};', common_cpp, re.M | re.S)
    parts.append(table.group(0))
    # GBA's actual reciprocal table and interpolation macro, not host division.
    reciprocal = re.search(r'^EWRAM_DATA ALIGN16 divTableInt divTable\[DIV_TABLE_SIZE\] = .*?^\};', common_cpp, re.M | re.S)
    parts.append(reciprocal.group(0).replace('EWRAM_DATA ALIGN16 ', ''))
    parts.append('#define GET_FRAME_T(x,n) (divTable[n] * (x))')
    for name in ('matrixPush_c', 'matrixSetIdentity_c', 'matrixTranslateRel_c',
                 'matrixRotateX_c', 'matrixRotateY_c', 'matrixRotateZ_c',
                 'matrixRotateYXZ_c', 'matrixFrame_c'):
        parts.append(function(common_cpp, rf'void {name}\('))
    for sig in (r'int32 ItemObj::getFrames\(', r'const AnimFrame\* ItemObj::getFrame\(',
                r'const AABBs& ItemObj::getBoundingBox\(',
                r'int32 ItemObj::getSpheres\(', r'uint32 ItemObj::collideSpheres\(',
                r'vec3i ItemObj::getJoint\('):
        parts.append(function(item_h, sig))
    Path(out).write_text('\n\n'.join(parts) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
