#!/usr/bin/env python3
"""Emit the fixed-point tables src/math.c reads.

They are generated rather than transcribed from src/fixed because the sizes
are different and the sizes are the whole point. src/fixed's gSinCosTable is
4096 packed 32-bit entries -- 16 KB, in ROM, which is exactly where this
GSU-2 target cannot put a table: the 65816 reads dummy data from cartridge ROM while
the GSU holds the bus, so anything the host reads has to be resident in WRAM,
out of the same 32 KB the compiled code lives in.

So the tables here are as small as the game can stand:

  sin    1024 entries of int16, one turn, 2 KB
         angle resolution 64 of 65536, which is 0.35 degrees
  atan   129 entries of int16 over y/x in [0, 1], 258 bytes
         the derivative of atan is at most 1, so the error is under half a
         degree anywhere, and the octant reduction in phd_atan does the rest

Both are checked against libm by tools/fixedcheck, which is what says whether
"as small as the game can stand" was true.

FX3 permits concurrent CPU/FX ROM access. Its native logic PRNG additionally
uses 256 exact uint32 constant products (1 KB in FastROM, never copied to
WRAM). Four byte-indexed reads replace ten hardware multiplies without
changing the original LCG's sequence. GSU-2 and C_MOTION omit that table.
"""

import math
import sys

SIN_ENTRIES = 1024          # over one turn; phd_sin shifts the angle by 6
ATAN_ENTRIES = 128          # over y/x in [0, 1]; the table has one more, for 1.0
FIXED_ONE = 1 << 14         # 1.14, as src/fixed's table uses


def emit(f, name, values, per_line=12, ctype="int16"):
    # External names also let the cartridge's native math.asm read them.
    # math.c is the only translation unit that includes this header.
    f.write(f"const {ctype} {name}[] = {{\n")
    for i in range(0, len(values), per_line):
        f.write("    " + ", ".join(f"{v:6d}" for v in values[i:i + per_line]) + ",\n")
    f.write("};\n\n")


def main():
    out = sys.argv[1]

    sin = [int(round(math.sin(2 * math.pi * i / SIN_ENTRIES) * FIXED_ONE))
           for i in range(SIN_ENTRIES)]
    # 1.0 is not representable in 1.14 as a signed 16-bit value; the table
    # peaks at exactly FIXED_ONE, which is, so nothing needs clamping.

    atan = [int(round(math.atan(i / ATAN_ENTRIES) / (2 * math.pi) * 65536.0))
            for i in range(ATAN_ENTRIES + 1)]

    with open(out, "w") as f:
        f.write("/* generated by tools/mktables.py -- do not edit */\n\n")
        f.write(f"#define OL_SIN_ENTRIES  {SIN_ENTRIES}\n")
        f.write(f"#define OL_SIN_SHIFT    {16 - SIN_ENTRIES.bit_length() + 1}\n")
        f.write(f"#define OL_ATAN_ENTRIES {ATAN_ENTRIES}\n\n")
        emit(f, "olSinTable", sin)
        emit(f, "olAtanTable", atan)
        f.write("#if defined(OL_FX3) && !defined(OL_C_MOTION)\n")
        # Explicit low/high words avoid compiler-specific long widths.
        products = [(i * 0x41C64E6D) & 0xFFFFFFFF for i in range(256)]
        emit(f, "olRandProducts", [word for value in products
                                   for word in (value & 65535, value >> 16)],
             ctype="uint16")
        f.write("#endif\n")

    print(f"{out}: {SIN_ENTRIES} sin entries ({SIN_ENTRIES * 2} bytes), "
          f"{ATAN_ENTRIES + 1} atan entries ({(ATAN_ENTRIES + 1) * 2} bytes)")


if __name__ == "__main__":
    main()
