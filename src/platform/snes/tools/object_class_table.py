#!/usr/bin/env python3
"""Generate a native byte classification map from the executable C specification.

Only the original enum, required constants and two pure C function bodies are
compiled. Every unsigned 16-bit input above the byte map is checked before a
native guard can replace it. The target's C_MOTION cartridge remains the final
independent oracle for the target compiler and calling convention.
"""

import argparse
from pathlib import Path
import re
import shlex
import subprocess
import tempfile


def uncomment(source):
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.S)


def function(source, signature):
    match = re.search(r"(?ms)^" + re.escape(signature) + r"\s*\([^)]*\)\s*\{.*?^\}", source)
    if not match:
        raise ValueError("missing C definition: " + signature)
    return match.group(0)


def specification(source_dir, fx3=True):
    files = {name: (source_dir / name).read_text() for name in
             ("object.c", "object.h", "enemy.c", "item.h")}
    functions = "\n".join((function(files["enemy.c"], "int Enemy_row"),
                            function(files["object.c"], "unsigned int ItemObj_class")))
    enums = re.findall(r"(?s)\benum\s*\{.*?\}\s*;", files["object.h"])
    classes = next((enum for enum in enums if re.search(r"\bCLASS_NONE\b", uncomment(enum))), None)
    if classes is None:
        raise ValueError("missing CLASS_NONE enum in object.h")
    constants, alternatives = {}, {}
    for source in files.values():
        for name, value in re.findall(r"(?m)^\s*#define\s+([A-Z][A-Z0-9_]*)[ \t]+([^\n]+)", source):
            value = uncomment(value).strip()
            alternatives.setdefault(name, set()).add(value)
            constants[name] = value
    needed = set(re.findall(r"\b[A-Z][A-Z0-9_]*\b", uncomment(functions + classes))) & constants.keys()
    while True:
        expanded = needed | {name for key in needed for name in
                             re.findall(r"\b[A-Z][A-Z0-9_]*\b", constants[key]) if name in constants}
        if expanded == needed:
            break
        needed = expanded
    for name in needed:
        if len(alternatives[name]) != 1:
            raise ValueError("conflicting classification constant: " + name)
    defines = "\n".join("#define " + name + " " + constants[name] for name in sorted(needed))
    return ("#define OL_FX3 1\n" if fx3 else "") + defines + "\n" + classes + "\n" + functions


def compile_map(source_dir, compiler="cc", fx3=True):
    source = "#include <stdio.h>\n" + specification(source_dir, fx3) + r'''
int main(void)
{
    unsigned int type, result;
    if (CLASS_NONE > 255) return 2;
    printf("%u\n", CLASS_NONE);
    for (type = 0; type < 65536; type++) {
        result = ItemObj_class(type);
        if (result > 255) return 3;
        if (type < 256) printf("%u\n", result);
        else if (result != CLASS_NONE) {
            fprintf(stderr, "type %u resolves to class %u beyond byte map\n", type, result);
            return 4;
        }
    }
    return 0;
}
'''
    with tempfile.TemporaryDirectory(prefix="openlara-object-class-") as directory:
        root = Path(directory)
        c_source, executable = root / "class.c", root / "class"
        c_source.write_text(source)
        compiled = subprocess.run([*shlex.split(compiler), "-std=c99", "-O2", str(c_source), "-o", str(executable)],
                                  capture_output=True, text=True, timeout=30)
        if compiled.returncode:
            raise ValueError("classification C failed to compile:\n" + compiled.stderr)
        result = subprocess.run([str(executable)], capture_output=True, text=True, timeout=30)
        if result.returncode:
            raise ValueError("classification cannot use a guarded byte map: " +
                             (result.stderr.strip() or "class value exceeds one byte"))
        values = [int(value) for value in result.stdout.splitlines()]
        if len(values) != 257:
            raise ValueError("classification C did not emit exactly 256 table entries")
        return values[0], values[1:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--source-dir", type=Path, default=Path(__file__).resolve().parent.parent / "src")
    parser.add_argument("--cc", default="cc", help="host C compiler command (default: cc)")
    parser.add_argument("--fx3", type=int, choices=(0, 1), default=1, help="classification variant (default: FX3)")
    options = parser.parse_args()
    try:
        none, table = compile_map(options.source_dir, options.cc, bool(options.fx3))
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        parser.exit(1, "object_class_table: " + str(error) + "\n")
    lines = ["; Generated by tools/object_class_table.py from the original C definitions; FX3=" + str(options.fx3),
             ".DEFINE OBJECT_CLASS_NONE " + str(none)]
    lines += [".DB " + ",".join("$%02X" % value for value in table[start:start + 16])
              for start in range(0, 256, 16)]
    options.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
